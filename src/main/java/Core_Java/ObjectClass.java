class Laptop
{
    String model;
    int price;

    public String toString()
    {
        return "model = " + model + "," + "price = " + price;
    }
    // public boolean equals(Laptop obj1)
    // {
    //     return this.model.equals(obj1.model) &&  this.price == obj1.price;
    // }

    // generated by IDE source action
    @Override
    public int hashCode() 
    {
        final int prime = 31;
        int result = 1;
        result = prime * result + ((model == null) ? 0 : model.hashCode());
        result = prime * result + price;
        return result;
    }
    @Override
    public boolean equals(Object obj) 
    {
        if (this == obj)
            return true;
        if (obj == null)
            return false;
        if (getClass() != obj.getClass())
            return false;
        Laptop other = (Laptop) obj;
        if (model == null) 
        {
            if (other.model != null)
                return false;
        } 
        else if (!model.equals(other.model))
            return false;
        if (price != other.price)
            return false;
        return true;
    }
}
